def same_pattern(a, b):
    """Do two strings have the same letter pattern (e.g. ABBABB and XYYXYY)?"""
    return len(a) == len(b) and [a.index(c) for c in a] == [b.index(c) for c in b]


def primes(n):
    return {p for p in range(2, n + 1) if n % p == 0 and all(p % k for k in range(2, p))}


def race_orders():
    for order in itertools.permutations("ABCDE"):   # Ann, Ben, Cal, Dee, Eve; order[0] finished first
        pos = {r: i for i, r in enumerate(order)}
        if pos["C"] < pos["A"] < pos["B"] and pos["D"] == 4 and pos["E"] == pos["B"] + 1:
            yield order


